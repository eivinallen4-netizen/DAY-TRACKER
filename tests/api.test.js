import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { openDatabase } from '../server/database.js';
import { createApp } from '../server/app.js';

test('pairing, access boundaries, live updates and completion lifecycle',async t=>{
  const db=await openDatabase(':memory:');
  const {app,close}=createApp(db,{rateLimits:false});
  const server=app.listen(0,'127.0.0.1');await once(server,'listening');
  const base=`http://127.0.0.1:${server.address().port}`;
  t.after(()=>{close();server.closeAllConnections();server.close();db.close();});
  function client(){let cookie='';return {async call(path,method='GET',body){const r=await fetch(base+'/api'+path,{method,headers:{cookie,...(method!=='GET'?{'Content-Type':'application/json'}:{})},body:method!=='GET'?JSON.stringify(body||{}):undefined});const set=r.headers.get('set-cookie');if(set)cookie=set.split(';')[0];return {status:r.status,data:await r.json()};},get cookie(){return cookie;}};}
  const tv=client(),phone=client(),outsider=client();
  assert.equal((await tv.call('/state')).status,401);
  assert.equal((await tv.call('/workspaces','POST',{timezone:'America/Los_Angeles'})).status,201);
  const before=(await tv.call('/state')).data;
  const pairing=(await tv.call('/pair','POST',{})).data;
  assert.equal(pairing.code.length,8);
  assert.equal((await phone.call('/pair/claim','POST',{code:pairing.code})).status,200);
  assert.equal((await outsider.call('/pair/claim','POST',{code:pairing.code})).status,400);
  assert.equal((await phone.call('/state')).data.workspace,before.workspace);
  const revoked=(await tv.call('/pair','POST',{})).data;
  await tv.call('/pair','POST',{});
  assert.equal((await outsider.call('/pair/claim','POST',{code:revoked.code})).status,400);
  await db.execute('UPDATE pairing_codes SET expires_at=0');
  const expired=(await tv.call('/pair','POST',{})).data;
  await db.execute('UPDATE pairing_codes SET expires_at=0');
  assert.equal((await outsider.call('/pair/claim','POST',{code:expired.code})).status,400);
  await outsider.call('/workspaces','POST',{});
  const eventAbort=new AbortController();
  const stream=await fetch(base+'/api/events',{headers:{cookie:tv.cookie},signal:eventAbort.signal});
  const reader=stream.body.getReader();
  assert.match(new TextDecoder().decode((await reader.read()).value),/connected/);
  const created=await phone.call('/tasks','POST',{title:'Read 20 minutes',kind:'daily',start_day:before.today});
  assert.equal(created.status,201);
  const change=await Promise.race([reader.read(),new Promise((_,reject)=>{const timer=setTimeout(()=>reject(Error('No SSE event')),3000);timer.unref();})]);
  assert.match(new TextDecoder().decode(change.value),/change/);eventAbort.abort();
  const id=created.data.id;
  assert.equal((await outsider.call(`/tasks/${id}/completion`,'PUT',{day:before.today,done:true})).status,404);
  assert.equal((await phone.call(`/tasks/${id}/completion`,'PUT',{day:'2099-01-01',done:true})).status,400);
  assert.equal((await phone.call(`/tasks/${id}/completion`,'PUT',{day:before.today,done:true})).status,200);
  await phone.call(`/tasks/${id}/completion`,'PUT',{day:before.today,done:true});
  let state=(await tv.call('/state')).data;
  assert.equal(state.metrics.xp,10);assert.equal(state.metrics.streak,1);assert.equal(state.completions.length,1);
  await phone.call(`/tasks/${id}/completion`,'PUT',{day:before.today,done:false});
  assert.equal((await tv.call('/state')).data.metrics.xp,0);
  await phone.call(`/tasks/${id}/completion`,'PUT',{day:before.today,done:true});
  await phone.call(`/tasks/${id}`,'PATCH',{title:'Read a chapter'});
  assert.equal((await tv.call('/state')).data.tasks[0].title,'Read a chapter');
  await phone.call(`/tasks/${id}`,'DELETE');
  state=(await tv.call('/state')).data;assert.equal(state.tasks[0].archived,1);assert.equal(state.metrics.xp,10);
  assert.equal((await outsider.call('/state')).data.tasks.length,0);
  const csrf=await fetch(base+'/api/tasks',{method:'POST',headers:{cookie:phone.cookie,'Content-Type':'application/json',origin:'https://evil.example'},body:JSON.stringify({title:'Bad'})});
  assert.equal(csrf.status,403);
});
